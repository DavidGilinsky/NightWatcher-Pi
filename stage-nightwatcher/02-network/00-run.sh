#!/bin/bash -e
# ---------------------------------------------------------------------------
# Author:        David Gilinsky
# File:          stage-nightwatcher/02-network/00-run.sh
# Purpose:       Install the appliance's network layer: the shared shell
#                library, the radio and access-point scripts, and the units
#                that run them. Also bakes the image's build-time defaults into
#                /etc/nightwatcher-pi/appliance.defaults, which is what first
#                boot starts from.
# Created:       2026-07-27
# Last Modified: 2026-07-27
# Version:       0.1.0
# License:       GPL-3.0-or-later
# ---------------------------------------------------------------------------

LIB="${ROOTFS_DIR}/usr/local/lib/nightwatcher-pi"
UNITS="${ROOTFS_DIR}/etc/systemd/system"

install -v -d "${LIB}"
install -v -m 644 files/nw-common.sh "${LIB}/nw-common.sh"
install -v -m 755 files/nw-radio-setup.sh "${LIB}/nw-radio-setup.sh"
install -v -m 755 files/nw-ap.sh "${LIB}/nw-ap.sh"
install -v -m 755 files/nw-uplink.sh "${LIB}/nw-uplink.sh"
install -v -m 755 files/nw-mdns-alias.sh "${LIB}/nw-mdns-alias.sh"
install -v -m 755 files/nw-portal.sh "${LIB}/nw-portal.sh"

install -v -m 644 files/nightwatcher-radio.service "${UNITS}/nightwatcher-radio.service"
install -v -m 644 files/nightwatcher-ap.service "${UNITS}/nightwatcher-ap.service"
install -v -m 644 files/nightwatcher-mdns-alias.service "${UNITS}/nightwatcher-mdns-alias.service"
install -v -m 644 files/nightwatcher-portal.service "${UNITS}/nightwatcher-portal.service"

# What this image was built to be. First boot copies these into appliance.conf
# and then edits that copy, so the defaults stay visible for comparison after an
# operator has changed things.
install -v -d "${ROOTFS_DIR}/etc/nightwatcher-pi"
cat > "${ROOTFS_DIR}/etc/nightwatcher-pi/appliance.defaults" << EOF
# ---------------------------------------------------------------------------
# File:          /etc/nightwatcher-pi/appliance.defaults
# Purpose:       Build-time defaults for this image. Do not edit: first boot
#                writes the unit's effective settings to appliance.conf, and
#                the web UI's RPi tab edits that. This file records what the
#                image shipped with.
# Generated by:  NightWatcher-Pi ${NWPI_VERSION:-0.1.0} image build
# License:       GPL-3.0-or-later
# ---------------------------------------------------------------------------
NWPI_VERSION='${NWPI_VERSION:-0.1.0}'
AP_SSID_PREFIX='${AP_SSID_PREFIX:-nightwatcher}'
AP_PASSPHRASE='${AP_PASSPHRASE:-nightwatcher}'
AP_ADDRESS='${AP_ADDRESS:-192.168.4.1/24}'
AP_CHANNEL='${AP_CHANNEL:-6}'
WIFI_COUNTRY='${WIFI_COUNTRY:-US}'
NW_PORT='8080'
EOF
chmod 644 "${ROOTFS_DIR}/etc/nightwatcher-pi/appliance.defaults"

on_chroot << 'EOF'
set -e
systemctl enable nightwatcher-radio.service
systemctl enable nightwatcher-ap.service
systemctl enable nightwatcher-mdns-alias.service
systemctl enable nightwatcher-portal.service
EOF
